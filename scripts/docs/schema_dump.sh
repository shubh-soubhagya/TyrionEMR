#!/usr/bin/env bash
# Schema-only dump of each service database into docs/db/<service>.sql, run inside the Postgres container.
# Source of truth is each service's migrations/; the dump is a readable snapshot of the result.
set -euo pipefail
PG_CONTAINER="${PG_CONTAINER:-graphgpt-postgres}"
PG_SUPERUSER="${PG_SUPERUSER:-postgres}"
OUT="$(cd "$(dirname "$0")/../.." && pwd)/docs/db"
mkdir -p "$OUT"
for pair in auth-svc:nephro_auth_db patient-svc:nephro_patient_db lab-svc:nephro_lab_db ai-svc:nephro_ai_db; do
  svc="${pair%%:*}"; db="${pair##*:}"
  {
    echo "-- Generated by 'make schema-dump'. Do not edit."
    echo "-- Source of truth: ${svc}/migrations/. Database: ${db}."
    docker exec "$PG_CONTAINER" pg_dump -U "$PG_SUPERUSER" -d "$db" --schema-only --no-owner --no-privileges
  } > "$OUT/${svc}.sql"
  echo "wrote docs/db/${svc}.sql"
done
